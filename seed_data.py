def seed_if_empty() -> int:
    """若 IP 库为空，插入种子。返回实际插入的 IP 数量。"""
    existing = ip_model.list_all_ips(limit=1)
    if existing:
        return 0
    inserted = 0
    for (name_cn, name_jp, aliases, kws, rank, chars) in SEED_IPS:
        ip_id = ip_model.insert_ip(
            name_cn=name_cn,
            name_jp=name_jp,
            aliases=aliases,
            heat_score=max(1, 100 - rank),
            heat_rank=rank,
            search_keywords=kws,
        )
        for cname_cn, cname_jp, grade, hs in chars:
            character_model.insert_character(
                ip_id=ip_id,
                name_cn=cname_cn,
                name_jp=cname_jp,
                grade=grade,
                heat_score=hs,
            )
        inserted += 1
    return inserted
